"""
Step 4 - Validate every generated row against the v2 quality rules.

Produces:
  validation_reports/validation_<tag>.csv   per-row pass/fail detail
  failed_rows/failed_<tag>.csv              rows that failed (for the fixer)
  batch_outputs/accepted_<tag>.csv          rows that passed

Run:
    python 04_validate.py --input batch_outputs/generated_50.csv
"""

import argparse
import re
from collections import Counter
from pathlib import Path

import pandas as pd
from config import (
    STOP_TOKEN, CITATION_LEAK_PHRASES, MIN_PASS_RATE,
    VALIDATION_REPORTS_DIR, FAILED_ROWS_DIR, BATCH_OUTPUTS_DIR,
)


def extract_numbers(text: str) -> set:
    return set(re.findall(r"-?\d+(?:,\d{3})*(?:\.\d+)?", str(text)))


def validate_row(row: dict) -> list:
    """Return a list of issue strings. Empty list = pass."""
    issues = []
    rt          = str(row.get("reasoning_target", "")).strip()
    answer_type = str(row.get("answer_type", "")).strip().lower()

    # Hard-fail: empty
    if not rt:
        issues.append("HARD_FAIL: reasoning_target is empty")
        return issues

    rt_lower = rt.lower()

    # Hard-fail: stop token
    token_count = rt.count(STOP_TOKEN)
    if token_count == 0:
        issues.append(f"HARD_FAIL: missing stop token {STOP_TOKEN!r}")
    elif token_count > 1:
        issues.append(f"HARD_FAIL: stop token appears {token_count}x (must be exactly 1)")

    # Hard-fail: required sections - check presence AND exact casing
    required_headers = [
        "Reasoning & Calculations:",
        "Values used:",
        "Calculation:",
        "Analysis:",
        "Final Answer:",
    ]
    for header in required_headers:
        if header not in rt:
            if header.lower() in rt_lower:
                issues.append(f"HARD_FAIL: section header wrong casing (must be exactly '{header}')")
            else:
                issues.append(f"HARD_FAIL: missing '{header}' section")

    # Citation leakage - only flag if the phrase is generated by the model.
    # Some questions or gold answers legitimately contain location wording.
    question_lower = str(row.get("question", "")).lower()
    answer_lower = str(row.get("answer", "")).lower()
    for phrase in CITATION_LEAK_PHRASES:
        p = phrase.lower()
        if p in rt_lower and p not in question_lower and p not in answer_lower:
            issues.append(f"CITATION_LEAK: contains '{phrase}'")

    # Answer-type template rules
    if answer_type == "arithmetic":
        if "No numerical calculation required" in rt:
            issues.append("ARITHMETIC_FAIL: says 'No numerical calculation required'")
        if "Calculation:" not in rt:
            issues.append("ARITHMETIC_FAIL: missing 'Calculation:' section")
        if "No financial analysis required." in rt:
            issues.append("ARITHMETIC_FAIL: Analysis section must contain real analysis, not the placeholder")

        # Percentage x100 check: Calculation result is a decimal but Final Answer states
        # a percent value ~100x larger — model forgot the x100 step.
        scale_val = str(row.get("scale", "") or "").lower()
        if "percent" in scale_val:
            calc_start  = rt.find("Calculation:")
            anal_start  = rt.find("Analysis:", calc_start + 1) if calc_start >= 0 else -1
            fa_start    = rt.find("Final Answer:")
            if calc_start >= 0 and anal_start > calc_start and fa_start >= 0:
                calc_text = rt[calc_start:anal_start]
                fa_text   = rt[fa_start:]
                calc_nums = re.findall(r"-?\d+(?:\.\d+)?", calc_text)
                fa_nums   = re.findall(r"-?\d+(?:\.\d+)?", fa_text)
                if calc_nums and fa_nums:
                    try:
                        last_calc  = float(calc_nums[-1])
                        expected   = abs(last_calc) * 100
                        # Check any number in FA (not just first — years like 2018 appear first)
                        fa_floats  = [float(n) for n in fa_nums]
                        fa_matches = any(abs(n - expected) < 0.1 for n in fa_floats)
                        if (0 < abs(last_calc) < 1.0 and fa_matches):
                            issues.append(
                                "ARITHMETIC_FAIL: percentage result not multiplied by 100 "
                                "(Calculation shows decimal, Final Answer shows percent value)"
                            )
                    except (ValueError, ZeroDivisionError):
                        pass

    if answer_type in ("span", "multi-span", "count"):
        if "Analysis:" in rt and "No financial analysis required." not in rt:
            issues.append(
                f"TEMPLATE_FAIL: {answer_type} Analysis section must be exactly "
                f"'No financial analysis required.' - no real analysis allowed"
            )

    # Count pre-filter warning (soft): Values used bullets == gold count suggests
    # only qualifying items were listed rather than all candidates
    if answer_type == "count":
        vu_start   = rt.find("Values used:")
        calc_start = rt.find("Calculation:", vu_start + 1) if vu_start >= 0 else -1
        if vu_start >= 0 and calc_start > vu_start:
            vu_text      = rt[vu_start:calc_start]
            bullet_count = sum(1 for ln in vu_text.splitlines() if ln.strip().startswith("-"))
            gold_raw     = str(row.get("answer", "")).strip()
            try:
                gold_int = int(float(gold_raw))
                if bullet_count > 0 and bullet_count == gold_int:
                    issues.append(
                        f"COUNT_PREFILTER_WARNING: Values used has {bullet_count} bullet(s), "
                        f"equal to gold count ({gold_int}) - possible pre-filtering"
                    )
            except (ValueError, TypeError):
                pass

    # Number grounding (soft warning, not a hard fail)
    source_numbers = set()
    for field in ["question", "answer", "derivation", "table_text", "relevant_paragraphs_text"]:
        source_numbers.update(extract_numbers(str(row.get(field, ""))))

    reasoning_numbers = extract_numbers(rt)
    suspicious = {
        n for n in reasoning_numbers - source_numbers
        if float(n.replace(",", "")) > 1
    }
    if suspicious:
        issues.append(f"NUMBER_GROUNDING_WARNING: unverified numbers {suspicious}")

    return issues


def is_hard_failure(issues: list) -> bool:
    """A row fails if it has any issue that is not merely a warning."""
    hard_prefixes = (
        "HARD_FAIL",
        "CITATION_LEAK",
        "ARITHMETIC_FAIL",
        "TEMPLATE_FAIL",
    )
    return any(i.startswith(hard_prefixes) for i in issues)


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--input", required=True,
                        help="Generated CSV from 03_generate.py")
    args = parser.parse_args()

    input_path = Path(args.input)
    if not input_path.exists():
        print(f"ERROR: {input_path} not found.")
        return

    tag = input_path.stem.replace("generated_", "")

    df = pd.read_csv(input_path, encoding="utf-8")
    print(f"Validating {len(df)} rows from {input_path} ...")

    val_rows = []
    for _, row in df.iterrows():
        issues    = validate_row(row.to_dict())
        hard_fail = is_hard_failure(issues)
        val_rows.append({
            "row_id":            row["row_id"],
            "answer_type":       row["answer_type"],
            "validation_status": "fail" if hard_fail else "pass",
            "validation_issues": "; ".join(issues),
            "issue_count":       len(issues),
            "hard_fail_count":   sum(1 for i in issues if not i.startswith("NUMBER_GROUNDING")),
        })

    val_df = pd.DataFrame(val_rows)

    df = df.copy()
    df["validation_status"] = val_df["validation_status"].values
    df["validation_issues"] = val_df["validation_issues"].values

    for d in [VALIDATION_REPORTS_DIR, FAILED_ROWS_DIR, BATCH_OUTPUTS_DIR]:
        d.mkdir(parents=True, exist_ok=True)

    report_path   = VALIDATION_REPORTS_DIR / f"validation_{tag}.csv"
    failed_path   = FAILED_ROWS_DIR        / f"failed_{tag}.csv"
    accepted_path = BATCH_OUTPUTS_DIR      / f"accepted_{tag}.csv"

    val_df.to_csv(report_path,   index=False, encoding="utf-8")

    failed   = df[df["validation_status"] == "fail"]
    accepted = df[df["validation_status"] == "pass"]

    failed.to_csv(failed_path,   index=False, encoding="utf-8")
    accepted.to_csv(accepted_path, index=False, encoding="utf-8")

    total     = len(df)
    n_passed  = len(accepted)
    n_failed  = len(failed)
    pass_rate = n_passed / total if total else 0

    print(f"\n{'='*55}")
    print(f"  VALIDATION SUMMARY")
    print(f"{'='*55}")
    print(f"  Total:    {total}")
    print(f"  Passed:   {n_passed}  ({pass_rate*100:.1f}%)")
    print(f"  Failed:   {n_failed}")
    print(f"\n  By answer type:")
    for atype, grp in df.groupby("answer_type"):
        p = (grp["validation_status"] == "pass").sum()
        print(f"    {atype:<12}  {p}/{len(grp)} passed")

    if n_failed:
        print(f"\n  Top failure reasons:")
        all_issues = "; ".join(
            val_df.loc[val_df["validation_status"] == "fail", "validation_issues"]
        )
        counts = Counter(
            i.split(":")[0].strip()
            for i in all_issues.split("; ")
            if i.strip()
        )
        for reason, count in counts.most_common(8):
            print(f"    {reason}: {count}")

    print(f"\n  Validation report -> {report_path}")
    print(f"  Failed rows       -> {failed_path}")
    print(f"  Accepted rows     -> {accepted_path}")

    if pass_rate < MIN_PASS_RATE:
        print(f"\n  WARNING: Pass rate {pass_rate*100:.1f}% is below the {MIN_PASS_RATE*100:.0f}% target.")
        print(f"  Fix the prompt in 03_generate.py before scaling up.")
    else:
        print(f"\n  PASS: Pass rate {pass_rate*100:.1f}% meets the target.")
        if n_failed:
            print(f"  Next step: python 05_fix.py --input {failed_path}")
        else:
            print(f"  Next step: python 06_finalize.py")


if __name__ == "__main__":
    main()
